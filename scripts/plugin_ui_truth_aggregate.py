#!/usr/bin/env python3
"""Aggregate filled Plugin UI Truth checklists into final PASS/FAIL certification.

Reads scenario_* folders generated by scripts/plugin_ui_truth_cert.py.
Each scenario should have operator_checklist.md filled with:
- screenshot_path
- plugin_log_snippet_path
- PASS / FAIL / NOT_PROVEN
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
import sys
from dataclasses import dataclass


CHECK_RE = re.compile(r"PASS\s*/\s*FAIL\s*/\s*NOT_PROVEN\s*:\s*(.*)", re.IGNORECASE)
SCREENSHOT_RE = re.compile(r"screenshot_path\s*:\s*(.*)", re.IGNORECASE)
LOG_RE = re.compile(r"plugin_log_snippet_path\s*:\s*(.*)", re.IGNORECASE)


@dataclass
class ScenarioResult:
    scenario_id: str
    title: str
    mark: str
    screenshot_path: str
    log_path: str
    has_backend_truth: bool
    checklist_path: str


def parse_operator_checklist(path: pathlib.Path) -> tuple[str, str, str]:
    mark = "NOT_PROVEN"
    screenshot = ""
    log = ""
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = CHECK_RE.search(line)
        if m:
            raw = m.group(1).strip().upper()
            if raw.startswith("PASS"):
                mark = "PASS"
            elif raw.startswith("FAIL"):
                mark = "FAIL"
            elif raw.startswith("NOT_PROVEN"):
                mark = "NOT_PROVEN"
        s = SCREENSHOT_RE.search(line)
        if s and not screenshot:
            screenshot = s.group(1).strip()
        l = LOG_RE.search(line)
        if l and not log:
            log = l.group(1).strip()
    return mark, screenshot, log


def detect_title(scenario_dir: pathlib.Path) -> str:
    backend_truth_path = scenario_dir / "backend_truth.json"
    if backend_truth_path.is_file():
        try:
            data = json.loads(backend_truth_path.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                outcome = data.get("outcome")
                ask_path = data.get("ask_path")
                expected = data.get("expected_outcome")
                parts = []
                if ask_path:
                    parts.append(f"ask_path={ask_path}")
                if outcome:
                    parts.append(f"outcome={outcome}")
                if expected and expected != outcome:
                    parts.append(f"expected={expected}")
                if parts:
                    return ", ".join(parts)
        except Exception:
            pass
    return "(title not detected)"


def main() -> int:
    parser = argparse.ArgumentParser(description="Aggregate plugin UI truth checklists into certification summary.")
    parser.add_argument("--artifact-root", required=True, help="Path to plugin_ui_truth_* artifact folder")
    parser.add_argument("--strict", action="store_true", help="Exit non-zero if any scenario is FAIL or NOT_PROVEN")
    args = parser.parse_args()

    root = pathlib.Path(args.artifact_root).resolve()
    if not root.is_dir():
        print(f"[FAIL] artifact root not found: {root}", file=sys.stderr)
        return 2

    scenario_dirs = sorted([p for p in root.iterdir() if p.is_dir() and p.name.startswith("scenario_")])
    if not scenario_dirs:
        print(f"[FAIL] no scenario_* folders found in {root}", file=sys.stderr)
        return 2

    results: list[ScenarioResult] = []
    for sd in scenario_dirs:
        sid = sd.name.replace("scenario_", "")
        checklist = sd / "operator_checklist.md"
        backend_truth = sd / "backend_truth.json"
        if checklist.is_file():
            mark, screenshot, log_path = parse_operator_checklist(checklist)
        else:
            mark, screenshot, log_path = "NOT_PROVEN", "", ""
        results.append(
            ScenarioResult(
                scenario_id=sid,
                title=detect_title(sd),
                mark=mark,
                screenshot_path=screenshot,
                log_path=log_path,
                has_backend_truth=backend_truth.is_file(),
                checklist_path=str(checklist),
            )
        )

    counts = {
        "PASS": sum(1 for r in results if r.mark == "PASS"),
        "FAIL": sum(1 for r in results if r.mark == "FAIL"),
        "NOT_PROVEN": sum(1 for r in results if r.mark == "NOT_PROVEN"),
        "TOTAL": len(results),
    }

    overall = "PASS"
    if counts["FAIL"] > 0:
        overall = "FAIL"
    elif counts["NOT_PROVEN"] > 0:
        overall = "NOT_PROVEN"

    summary = {
        "schema_version": "plugin_ui_truth_cert_summary.v1",
        "generated_utc": dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        "artifact_root": str(root),
        "counts": counts,
        "overall": overall,
        "scenarios": [
            {
                "scenario_id": r.scenario_id,
                "title": r.title,
                "mark": r.mark,
                "has_backend_truth": r.has_backend_truth,
                "screenshot_path": r.screenshot_path,
                "plugin_log_snippet_path": r.log_path,
                "checklist_path": r.checklist_path,
            }
            for r in results
        ],
    }

    out_json = root / "cert_summary.json"
    out_md = root / "cert_summary.md"
    out_json.write_text(json.dumps(summary, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")

    md_lines = [
        "# Plugin UI Truth Certification Summary\n",
        f"Generated UTC: {summary['generated_utc']}\n",
        f"Artifact root: {root}\n",
        f"Overall: {overall}\n\n",
        "## Counts\n",
        f"- PASS: {counts['PASS']}\n",
        f"- FAIL: {counts['FAIL']}\n",
        f"- NOT_PROVEN: {counts['NOT_PROVEN']}\n",
        f"- TOTAL: {counts['TOTAL']}\n\n",
        "## Scenario Results\n",
        "| ID | Mark | Title/Truth Hint | Screenshot | Plugin log |\n",
        "|---|---|---|---|---|\n",
    ]
    for r in results:
        md_lines.append(
            f"| {r.scenario_id} | {r.mark} | {r.title} | {r.screenshot_path or '(missing)'} | {r.log_path or '(missing)'} |\n"
        )

    out_md.write_text("".join(md_lines), encoding="utf-8")

    print(f"[OK] Wrote {out_json}")
    print(f"[OK] Wrote {out_md}")
    print(f"[INFO] Overall={overall} PASS={counts['PASS']} FAIL={counts['FAIL']} NOT_PROVEN={counts['NOT_PROVEN']}")

    if args.strict and overall != "PASS":
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
